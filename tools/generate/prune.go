package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// generatedMarker is the first line of every Go file the generator emits. It is
// the discriminator pruneStale uses to tell its own output from a handwritten
// file, and it is deliberately the only one: tracking what this run wrote is
// enough to find a *candidate* for deletion, but not enough to justify deleting
// it, because a config typo or a half-finished refactor can make the generator
// legitimately skip a file it used to write. Requiring the marker means the
// worst a bug can do is delete something the generator can reproduce.
const generatedMarker = "// Code generated by tools/generate; DO NOT EDIT."

// emitted records the absolute path of every file the generator wrote this run.
// Populated by writeGenerated, drained by pruneStale.
var emitted = map[string]bool{}

// writeGenerated writes a generated file and records it. Every write in the
// generator goes through here rather than calling os.WriteFile directly — a
// write that bypasses it looks stale to pruneStale and gets deleted on the next
// run, which is a self-inflicted and confusing failure.
func writeGenerated(path string, data []byte, perm os.FileMode) error {
	if err := os.WriteFile(path, data, perm); err != nil {
		return err
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		// Recording is best-effort relative to writing: a path that cannot be
		// absolutised cannot be compared against a directory listing either, so
		// the file simply never becomes a prune candidate.
		log.Printf("warning: cannot absolutise %s for stale-file tracking: %v", path, err)
		return nil
	}
	emitted[abs] = true
	return nil
}

// pruneStale deletes generated files that this run did not write.
//
// It exists because the generator is whitelist-driven: removing an operation
// from config.json (or Jamf withdrawing a path from a spec) stops a file being
// emitted but does not remove the one already on disk. The stale file keeps
// compiling against types that types.go no longer declares, so the build breaks
// — and CI's `git diff --exit-code` check cannot catch it, because an untouched
// file produces no diff. The v1872 ingest left 12 such files behind across pro
// and proclassic; they had to be found by diffing the write log against the
// directory listing, which is what this now does automatically.
//
// Three guards, each earning its place:
//
//   - Only directories this run wrote into are considered. A run that wrote
//     nothing — a config that failed to load, a spec set that resolved to
//     nothing — therefore prunes nothing rather than emptying the tree.
//   - Only files carrying generatedMarker are deleted. Handwritten files living
//     alongside generated ones (jamfplatform/client.go, the acc_*_test.go
//     suite) are left untouched, and so is anything the generator cannot
//     reproduce.
//   - Only .go files. Published specs under api/ are pruned separately by
//     pruneStaleSpecs, which needs a different guard.
//
// Deleting rather than reporting is deliberate: the deletion shows up in git,
// so it is reviewable and CI still fails for a contributor who forgot to
// regenerate, while `make generate` alone leaves the tree correct.
func pruneStale(root string) error {
	dirs := writtenDirs(".go")
	if len(dirs) == 0 {
		return nil
	}
	var pruned, kept []string
	for _, dir := range dirs {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return fmt.Errorf("reading %s: %w", dir, err)
		}
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
				continue
			}
			path := filepath.Join(dir, e.Name())
			if emitted[path] {
				continue
			}
			marked, err := hasGeneratedMarker(path)
			if err != nil {
				return fmt.Errorf("inspecting %s: %w", path, err)
			}
			rel := relToRoot(root, path)
			if !marked {
				kept = append(kept, rel)
				continue
			}
			if err := os.Remove(path); err != nil {
				return fmt.Errorf("removing stale %s: %w", path, err)
			}
			pruned = append(pruned, rel)
		}
	}
	sort.Strings(pruned)
	for _, p := range pruned {
		log.Printf("pruned stale generated file %s", p)
	}
	if len(pruned) > 0 {
		log.Printf("pruned %d stale generated file(s); %d handwritten file(s) left alone", len(pruned), len(kept))
	}
	return nil
}

// pruneStaleSpecs deletes published specs in cfg.SpecDir that this run did not
// write. Separate from pruneStale because a JSON spec carries no marker comment,
// so the only thing standing between a bug and the whole published surface is
// the caller: it must only run when publishSpecs actually ran. In CI the source
// specs are absent, publishing is skipped, and calling this there would delete
// every spec the generator had just read its own input from.
func pruneStaleSpecs(root, specDir string) error {
	if specDir == "" {
		return nil
	}
	dir, err := filepath.Abs(filepath.Join(root, specDir))
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("reading %s: %w", dir, err)
	}
	// A publish run that emitted nothing into this directory is not evidence
	// that every file in it is stale — it is evidence that something went wrong
	// upstream. Same guard as pruneStale's empty-dirs case.
	wrote := false
	for _, e := range entries {
		if emitted[filepath.Join(dir, e.Name())] {
			wrote = true
			break
		}
	}
	if !wrote {
		return nil
	}
	var pruned []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		path := filepath.Join(dir, e.Name())
		if emitted[path] {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing stale %s: %w", path, err)
		}
		pruned = append(pruned, relToRoot(root, path))
	}
	sort.Strings(pruned)
	for _, p := range pruned {
		log.Printf("pruned stale published spec %s", p)
	}
	return nil
}

// writtenDirs returns the distinct directories this run wrote a file with the
// given extension into.
func writtenDirs(ext string) []string {
	seen := map[string]bool{}
	var dirs []string
	for path := range emitted {
		if !strings.HasSuffix(path, ext) {
			continue
		}
		dir := filepath.Dir(path)
		if !seen[dir] {
			seen[dir] = true
			dirs = append(dirs, dir)
		}
	}
	sort.Strings(dirs)
	return dirs
}

// hasGeneratedMarker reports whether the file's first line is generatedMarker.
// Only the head of the file is read: the marker is always first, and these files
// run to tens of thousands of lines.
func hasGeneratedMarker(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer func() { _ = f.Close() }()
	buf := make([]byte, len(generatedMarker)+2)
	n, err := f.Read(buf)
	if err != nil && n == 0 {
		// An empty file carries no marker, which is the correct answer rather
		// than an error: it is not something the generator produced.
		return false, nil
	}
	return bytes.HasPrefix(buf[:n], []byte(generatedMarker)), nil
}

// relToRoot renders a path relative to the repo root for logging, falling back
// to the absolute path when it lies outside.
func relToRoot(root, path string) string {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return path
	}
	rel, err := filepath.Rel(absRoot, path)
	if err != nil || strings.HasPrefix(rel, "..") {
		return path
	}
	return rel
}
